/**
 * Get an icon by name
 * @param {string} name - Icon name (e.g., 'play', 'piano', 'music-note')
 * @param {string} size - Size preset or custom size
 * @returns {string} SVG markup string
 */
export function getIcon(name, size = 'md') {
    const iconFn = iconMap[name];
    if (iconFn) {
        return iconFn(size);
    }
    console.warn(`Icon "${name}" not found`);
    return '';
}

/**
 * Inject an icon into a DOM element
 * @param {HTMLElement} element - Target element
 * @param {string} name - Icon name
 * @param {string} size - Size preset
 * @param {string} position - 'before', 'after', or 'replace'
 */
export function injectIcon(element, name, size = 'md', position = 'before') {
    const iconHtml = getIcon(name, size);
    if (!iconHtml) return;
    
    if (position === 'replace') {
        element.innerHTML = iconHtml;
    } else if (position === 'before') {
        element.insertAdjacentHTML('afterbegin', iconHtml + ' ');
    } else if (position === 'after') {
        element.insertAdjacentHTML('beforeend', ' ' + iconHtml);
    }
}


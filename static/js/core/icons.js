/**
 * Creates an SVG element with consistent styling
 * @param {string} pathData - The SVG path d attribute
 * @param {string} size - Size preset or custom size
 * @param {string} viewBox - SVG viewBox (default: "0 0 24 24")
 * @param {object} options - Additional options (className, title, etc.)
 * @returns {string} SVG markup string
 */
function createIcon(pathData, size = 'md', viewBox = '0 0 24 24', options = {}) {
    const sizeValue = ICON_SIZES[size] || size;
    const className = options.className ? ` class="${options.className}"` : ' class="icon"';
    const title = options.title ? `<title>${options.title}</title>` : '';
    const paths = Array.isArray(pathData) ? pathData.join('') : `<path d="${pathData}"/>`;
    
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${sizeValue}" height="${sizeValue}" viewBox="${viewBox}" fill="currentColor" style="vertical-align: middle;"${className}>${title}${paths}</svg>`;
}

